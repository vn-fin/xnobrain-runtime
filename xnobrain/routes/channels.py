"""Agent channel routes: inbound ingestion and the Zalo product surface."""

from ..models.channels import (
    ChannelInboundMessage,
    ChannelInboundResult,
    ChannelListResult,
    ChannelPairingApproveResult,
    ChannelPairingDenyResult,
    ChannelPairingListResult,
    ChannelPairingRequest,
    ChannelPairingRevokeRequest,
    ChannelPairingRevokeResult,
    ChannelQrResult,
    ChannelState,
    ChannelTurnRequest,
    ChannelTurnResult,
    ChannelZaloBotPatch,
    ChannelZaloBotUpdate,
    ChannelZaloPatch,
    ChannelZaloUpdate,
)
from .definition import route

ROUTES = (
    route(
        "GET",
        "/agents/{agent_id}/channels",
        "channels_list",
        tags=("Channels",),
        response_data=ChannelListResult,
    ),
    route(
        "PUT",
        "/agents/{agent_id}/channels/zalo",
        "channels_zalo_update",
        ChannelZaloUpdate,
        tags=("Channels",),
        response_data=ChannelState,
    ),
    route(
        "PATCH",
        "/agents/{agent_id}/channels/zalo",
        "channels_zalo_patch",
        ChannelZaloPatch,
        tags=("Channels",),
        response_data=ChannelState,
    ),
    route(
        "GET",
        "/agents/{agent_id}/channels/zalo/qr",
        "channels_zalo_qr",
        tags=("Channels",),
        response_data=ChannelQrResult,
    ),
    route(
        "POST",
        "/agents/{agent_id}/channels/zalo/logout",
        "channels_zalo_logout",
        tags=("Channels",),
        response_data=ChannelState,
    ),
    route(
        "PUT",
        "/agents/{agent_id}/channels/zalo_bot",
        "channels_zalo_bot_update",
        ChannelZaloBotUpdate,
        tags=("Channels",),
        response_data=ChannelState,
    ),
    route(
        "PATCH",
        "/agents/{agent_id}/channels/zalo_bot",
        "channels_zalo_bot_patch",
        ChannelZaloBotPatch,
        tags=("Channels",),
        response_data=ChannelState,
    ),
    route(
        "POST",
        "/agents/{agent_id}/channels/zalo_bot/logout",
        "channels_zalo_bot_logout",
        tags=("Channels",),
        response_data=ChannelState,
    ),
    route(
        "GET",
        "/agents/{agent_id}/channels/{platform}/pairings",
        "channels_pairings_list",
        tags=("Channels",),
        response_data=ChannelPairingListResult,
    ),
    route(
        "POST",
        "/agents/{agent_id}/channels/{platform}/pairings/approve",
        "channels_pairings_approve",
        ChannelPairingRequest,
        tags=("Channels",),
        response_data=ChannelPairingApproveResult,
    ),
    route(
        "POST",
        "/agents/{agent_id}/channels/{platform}/pairings/deny",
        "channels_pairings_deny",
        ChannelPairingRequest,
        tags=("Channels",),
        response_data=ChannelPairingDenyResult,
    ),
    route(
        "POST",
        "/agents/{agent_id}/channels/{platform}/pairings/revoke",
        "channels_pairings_revoke",
        ChannelPairingRevokeRequest,
        tags=("Channels",),
        response_data=ChannelPairingRevokeResult,
    ),
    route(
        "POST",
        "/internal/channels/messages",
        "channels_internal_message",
        ChannelInboundMessage,
        tags=("Channels",),
        response_data=ChannelInboundResult,
    ),
    route(
        "POST",
        "/internal/channels/turn",
        "channels_internal_turn",
        ChannelTurnRequest,
        tags=("Channels",),
        response_data=ChannelTurnResult,
    ),
)
